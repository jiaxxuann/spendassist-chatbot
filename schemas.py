from pydantic import BaseModel, Field
from typing import List, Optional, Any

# ==========================================
# API Endpoint Schemas
# ==========================================

class ChatRequest(BaseModel):
    session_id: str = Field(..., description="Unique identifier for the user session.")
    message: str = Field(..., description="The plain-language query from the user.")

class ChatResponse(BaseModel):
    answer: str = Field(..., description="The plain-language answer generated by the agent.")
    citations: List[str] = Field(
        default_factory=list, 
        description="References to policy clauses or transaction IDs supporting the answer."
    )
    actions: List[Any] = Field(
        default_factory=list, 
        description="List of actions taken, such as a drafted expense claim awaiting approval."
    )

# ==========================================
# Tool Input Schemas
# ==========================================

class QuerySpendInput(BaseModel):
    employee_id: Optional[str] = Field(None, description="The ID of the employee if querying individual spend.")
    department: Optional[str] = Field(None, description="The department name if querying team budgets or top merchants.")
    category: Optional[str] = Field(None, description="Specific expense category (e.g., travel, meals, software, supplies).")
    time_period: Optional[str] = Field(None, description="The time period for the query (e.g., 'last quarter', 'this year').")

class DraftExpenseClaimInput(BaseModel):
    employee_id: str = Field(..., description="The ID of the employee submitting the claim.")
    amount: float = Field(..., description="The transaction amount.")
    category: str = Field(..., description="The expense category (travel, meals, software, supplies).")
    merchant: str = Field(..., description="The vendor or merchant name.")
    transaction_date: str = Field(..., description="The date of the transaction in YYYY-MM-DD format.")