"""
api/main.py — SpendAssist REST API

Entry point for all HTTP interactions with the SpendAssist chatbot backend.
Built with FastAPI; wired to the LangGraph orchestrator in agent/graph.py.
"""

import logging
import os

from dotenv import load_dotenv
load_dotenv()

# --- DEBUG: CHECK API KEY ---
api_key = os.getenv("GROQ_API_KEY")
if api_key:
    print(f"✅ API Key loaded successfully! (Starts with: {api_key[:4]}...)")
else:
    print("❌ ERROR: API Key is MISSING or NOT LOADED!")
# -----------------------------

from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse

from agent.graph import run_agent
from schemas import ChatRequest, ChatResponse

# ---------------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------------

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# App initialisation
# ---------------------------------------------------------------------------

app = FastAPI(
    title="SpendAssist API",
    description=(
        "REST API for the SpendAssist expense-management chatbot. "
        "Accepts natural-language queries and returns policy-grounded answers "
        "generated by the LangGraph agent orchestrator."
    ),
    version="1.0.0",
)

# ---------------------------------------------------------------------------
# Global exception handler — returns a consistent 500 envelope
# ---------------------------------------------------------------------------

@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Catch-all handler for unexpected exceptions.

    Logs the full traceback server-side and returns a safe 500 response to
    the client so that internal implementation details are never exposed.
    """
    logger.exception(
        "Unhandled exception on %s %s", request.method, request.url.path
    )
    return JSONResponse(
        status_code=500,
        content={
            "detail": "An unexpected internal error occurred. Please try again later."
        },
    )

# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------

@app.get(
    "/health",
    summary="Health Check",
    tags=["Ops"],
    response_description="Returns the API status and current version.",
)
async def health_check() -> dict:
    """Lightweight liveness probe.

    Returns a JSON object confirming the service is running and its version.
    Intended for use by load-balancers, container orchestrators, and CI pipelines.
    """
    return {"status": "healthy", "version": "1.0.0"}


@app.post(
    "/chat",
    response_model=ChatResponse,
    summary="Chat with the SpendAssist Agent",
    tags=["Agent"],
    response_description="Agent answer with optional policy citations and drafted actions.",
)
async def chat(request: ChatRequest) -> ChatResponse:
    """Accept a natural-language expense query and return an agent response.

    Delegates to the LangGraph orchestrator (``agent/graph.py``) which
    invokes ``query_spend`` and/or ``draft_expense_claim`` as needed before
    synthesising a policy-grounded plain-language answer.

    Returns:
        ``ChatResponse`` containing:

        - ``answer``    — The agent's final plain-language response.
        - ``citations`` — Clause IDs (e.g. "Clause 1.2") and transaction IDs
                          found in the answer.
        - ``actions``   — Draft claim dicts produced by ``draft_expense_claim``
                          during this turn, each carrying
                          ``"status": "awaiting_manager_approval"``.

    Raises:
        HTTPException (500): Propagated via the global exception handler for
            any unexpected error during agent execution.
    """
    logger.info(
        "POST /chat | session_id=%s | message_preview='%.80s'",
        request.session_id,
        request.message,
    )

    result = run_agent(
        session_id=request.session_id,
        message=request.message,
    )

    return ChatResponse(
        answer=result["answer"],
        citations=result["citations"],
        actions=result["actions"],
    )

