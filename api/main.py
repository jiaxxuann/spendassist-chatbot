"""
api/main.py — SpendAssist REST API

Entry point for all HTTP interactions with the SpendAssist chatbot backend.
Built with FastAPI; structured for later connection to the LangGraph orchestrator.
"""

import logging

from fastapi import FastAPI, Request
from fastapi.responses import JSONResponse

from schemas import ChatRequest, ChatResponse

# ---------------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------------

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
)
logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# App initialisation
# ---------------------------------------------------------------------------

app = FastAPI(
    title="SpendAssist API",
    description=(
        "REST API for the SpendAssist expense-management chatbot. "
        "Accepts natural-language queries and returns policy-grounded answers "
        "generated by the LangGraph agent orchestrator."
    ),
    version="1.0.0",
)

# ---------------------------------------------------------------------------
# Global exception handler — returns a consistent 500 envelope
# ---------------------------------------------------------------------------

@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Catch-all handler for unexpected exceptions.

    Logs the full traceback server-side and returns a safe 500 response to
    the client so that internal implementation details are never exposed.
    """
    logger.exception(
        "Unhandled exception on %s %s", request.method, request.url.path
    )
    return JSONResponse(
        status_code=500,
        content={
            "detail": "An unexpected internal error occurred. Please try again later."
        },
    )

# ---------------------------------------------------------------------------
# Routes
# ---------------------------------------------------------------------------

@app.get(
    "/health",
    summary="Health Check",
    tags=["Ops"],
    response_description="Returns the API status and current version.",
)
async def health_check() -> dict:
    """Lightweight liveness probe.

    Returns a JSON object confirming the service is running and its version.
    Intended for use by load-balancers, container orchestrators, and CI pipelines.
    """
    return {"status": "healthy", "version": "1.0.0"}


